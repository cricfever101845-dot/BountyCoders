"""Database connections and non-destructive schema migrations.

Production uses Supabase PostgreSQL via DATABASE_URL. SQLite remains available
for trusted local development when DATABASE_URL is not set.
"""
from __future__ import annotations

import os
import sqlite3
import time
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parent
DEFAULT_SQLITE_PATH = ROOT / "bountycoders.db"
MIGRATION_LOCK_ID = 914_205_771


class _PostgresCursor:
    """Keep the existing application's qmark SQL while using psycopg2."""

    def __init__(self, cursor):
        self._cursor = cursor

    def execute(self, statement, parameters=None):
        if statement.strip().upper() == "BEGIN IMMEDIATE":
            # psycopg2 starts a transaction on the first statement automatically.
            return self._cursor
        statement = statement.replace("?", "%s")
        return self._cursor.execute(statement, parameters)

    def executemany(self, statement, parameters):
        statement = statement.replace("?", "%s")
        return self._cursor.executemany(statement, parameters)

    def __getattr__(self, name):
        return getattr(self._cursor, name)


class _PostgresConnection:
    def __init__(self, connection):
        self._connection = connection

    def cursor(self, *args, **kwargs):
        return _PostgresCursor(self._connection.cursor(*args, **kwargs))

    def execute(self, statement, parameters=None):
        cursor = self.cursor()
        cursor.execute(statement, parameters)
        return cursor

    def __getattr__(self, name):
        return getattr(self._connection, name)


def is_postgres_enabled() -> bool:
    return bool(os.environ.get("DATABASE_URL", "").strip())


def connect_db() -> Any:
    """Open one short-lived connection. Callers must close it after each request."""
    database_url = os.environ.get("DATABASE_URL", "").strip()
    if os.environ.get("ENVIRONMENT", "development").strip().lower() == "production" and not database_url:
        raise RuntimeError("DATABASE_URL is required when ENVIRONMENT=production; refusing to create ephemeral SQLite data.")
    if database_url:
        try:
            import psycopg2
            from psycopg2.extras import RealDictCursor
        except ImportError as exc:  # pragma: no cover - deployment configuration
            raise RuntimeError(
                "PostgreSQL is configured but psycopg2-binary is not installed. "
                "Install the pinned requirements.txt dependencies."
            ) from exc

        attempts = max(1, min(int(os.environ.get("DB_CONNECT_ATTEMPTS", "3")), 5))
        for attempt in range(attempts):
            try:
                connection = psycopg2.connect(
                    database_url,
                    sslmode=os.environ.get("DB_SSLMODE", "require"),
                    connect_timeout=int(os.environ.get("DB_CONNECT_TIMEOUT", "5")),
                    application_name="bounty-coders",
                    cursor_factory=RealDictCursor,
                )
                break
            except psycopg2.OperationalError:
                if attempt + 1 == attempts:
                    raise
                time.sleep(min(0.25 * (2 ** attempt), 1.0))
        return _PostgresConnection(connection)

    sqlite_path = Path(os.environ.get("SQLITE_PATH", str(DEFAULT_SQLITE_PATH)))
    if not sqlite_path.is_absolute():
        sqlite_path = ROOT / sqlite_path
    sqlite_path.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(sqlite_path, timeout=5)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    conn.execute("PRAGMA busy_timeout = 5000")
    return conn


def _schema_statements(postgres: bool) -> list[str]:
    identity = "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if postgres else "INTEGER PRIMARY KEY AUTOINCREMENT"
    timestamp = "TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP" if postgres else "TIMESTAMP DEFAULT CURRENT_TIMESTAMP"
    return [
        f"""CREATE TABLE IF NOT EXISTS users (
            id {identity},
            username TEXT NOT NULL UNIQUE,
            email TEXT NOT NULL UNIQUE,
            password TEXT NOT NULL,
            total_bounty BIGINT NOT NULL DEFAULT 0,
            created_at {timestamp}
        )""",
        f"""CREATE TABLE IF NOT EXISTS courses (
            id TEXT PRIMARY KEY,
            name TEXT NOT NULL UNIQUE,
            description TEXT,
            language TEXT,
            created_at {timestamp}
        )""",
        """CREATE TABLE IF NOT EXISTS questions (
            id TEXT PRIMARY KEY,
            course_id TEXT NOT NULL REFERENCES courses(id),
            level TEXT NOT NULL,
            question_number INTEGER NOT NULL,
            question_text_1 TEXT NOT NULL,
            expected_output_1 TEXT NOT NULL,
            question_text_2 TEXT NOT NULL,
            expected_output_2 TEXT NOT NULL,
            question_text_3 TEXT NOT NULL,
            expected_output_3 TEXT NOT NULL,
            opponent_name TEXT NOT NULL,
            language TEXT NOT NULL,
            UNIQUE(course_id, level, question_number)
        )""",
        f"""CREATE TABLE IF NOT EXISTS progress (
            id {identity},
            user_id INTEGER NOT NULL REFERENCES users(id),
            course_id TEXT NOT NULL REFERENCES courses(id),
            current_level TEXT NOT NULL DEFAULT 'easy',
            current_question_number INTEGER NOT NULL DEFAULT 1,
            completed INTEGER NOT NULL DEFAULT 0,
            session_questions TEXT,
            bounty_earned BIGINT NOT NULL DEFAULT 0,
            last_updated {timestamp}
        )""",
        f"""CREATE TABLE IF NOT EXISTS bounty_records (
            id {identity},
            user_id INTEGER NOT NULL REFERENCES users(id),
            course_id TEXT NOT NULL,
            course_name TEXT NOT NULL,
            bounty BIGINT NOT NULL DEFAULT 0,
            completed_at {timestamp}
        )""",
        """CREATE TABLE IF NOT EXISTS user_profiles (
            user_id INTEGER PRIMARY KEY REFERENCES users(id),
            display_name TEXT,
            pirate_group TEXT,
            avatar TEXT NOT NULL DEFAULT 'luffy'
        )""",
        """CREATE TABLE IF NOT EXISTS question_rotation (
            user_id INTEGER NOT NULL REFERENCES users(id),
            course_id TEXT NOT NULL,
            level TEXT NOT NULL,
            question_number INTEGER NOT NULL,
            last_alt INTEGER NOT NULL CHECK (last_alt BETWEEN 1 AND 3),
            PRIMARY KEY (user_id, course_id, level, question_number)
        )""",
        "CREATE INDEX IF NOT EXISTS idx_progress_user_course ON progress(user_id, course_id, completed)",
        "CREATE INDEX IF NOT EXISTS idx_bounty_records_user_course ON bounty_records(user_id, course_id)",
    ]


def _table_columns(conn: Any, postgres: bool, table: str) -> set[str]:
    cursor = conn.cursor()
    if postgres:
        cursor.execute(
            "SELECT column_name FROM information_schema.columns "
            "WHERE table_schema = 'public' AND table_name = %s",
            (table,),
        )
        return {row["column_name"] for row in cursor.fetchall()}
    cursor.execute(f"PRAGMA table_info({table})")
    return {row["name"] for row in cursor.fetchall()}


def _ensure_legacy_columns(conn: Any, postgres: bool) -> None:
    columns = _table_columns(conn, postgres, "users")
    if "password_hash" in columns and "password" not in columns:
        conn.cursor().execute("ALTER TABLE users RENAME COLUMN password_hash TO password")
        columns.remove("password_hash")
        columns.add("password")
    if "password" not in columns:
        raise RuntimeError("The users table has no password-hash column; migration stopped without changing user data.")

    additions = {
        "users": {"total_bounty": "BIGINT NOT NULL DEFAULT 0", "created_at": "TIMESTAMP"},
        "courses": {"description": "TEXT", "language": "TEXT", "created_at": "TIMESTAMP"},
        "progress": {
            "current_level": "TEXT NOT NULL DEFAULT 'easy'",
            "current_question_number": "INTEGER NOT NULL DEFAULT 1",
            "completed": "INTEGER NOT NULL DEFAULT 0",
            "session_questions": "TEXT",
            "bounty_earned": "BIGINT NOT NULL DEFAULT 0",
            "last_updated": "TIMESTAMP",
        },
        "bounty_records": {"bounty": "BIGINT NOT NULL DEFAULT 0", "completed_at": "TIMESTAMP"},
        "user_profiles": {
            "display_name": "TEXT",
            "pirate_group": "TEXT",
            "avatar": "TEXT DEFAULT 'luffy'",
        },
    }
    for table, definitions in additions.items():
        existing = _table_columns(conn, postgres, table)
        for column, definition in definitions.items():
            if column not in existing:
                conn.cursor().execute(f"ALTER TABLE {table} ADD COLUMN {column} {definition}")

    required_relationship_columns = {
        "users": {"id", "username", "email", "password"},
        "courses": {"id", "name"},
        "questions": {
            "id", "course_id", "level", "question_number", "question_text_1", "expected_output_1",
            "question_text_2", "expected_output_2", "question_text_3", "expected_output_3", "opponent_name", "language",
        },
        "progress": {"id", "user_id", "course_id"},
        "bounty_records": {"id", "user_id", "course_id", "course_name"},
        "user_profiles": {"user_id", "display_name", "pirate_group", "avatar"},
    }
    for table, required in required_relationship_columns.items():
        missing = required - _table_columns(conn, postgres, table)
        if missing:
            raise RuntimeError(
                f"The existing {table} table is missing required columns: {', '.join(sorted(missing))}. "
                "Migration stopped without dropping the table."
            )


def initialize_database(seed_reference_data: bool = True) -> None:
    """Apply idempotent migrations and seed missing reference data.

    The source database is never dropped or rewritten. PostgreSQL serializes
    concurrent first starts with a transaction-scoped advisory lock.
    """
    postgres = is_postgres_enabled()
    conn = connect_db()
    try:
        cursor = conn.cursor()
        if postgres:
            cursor.execute("SELECT pg_advisory_xact_lock(%s)", (MIGRATION_LOCK_ID,))
            cursor.execute(
                "CREATE TABLE IF NOT EXISTS schema_migrations "
                "(version TEXT PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP)"
            )
        else:
            cursor.execute(
                "CREATE TABLE IF NOT EXISTS schema_migrations "
                "(version TEXT PRIMARY KEY, applied_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP)"
            )

        for statement in _schema_statements(postgres):
            cursor.execute(statement)
        _ensure_legacy_columns(conn, postgres)
        if postgres:
            # The application connects directly as the database owner. RLS with
            # no browser-facing policies keeps Supabase's Data API closed.
            for table in ("users", "courses", "questions", "progress", "bounty_records", "user_profiles", "question_rotation"):
                cursor.execute(f"ALTER TABLE public.{table} ENABLE ROW LEVEL SECURITY")
        cursor.execute(
            "INSERT INTO schema_migrations (version) VALUES (%s) ON CONFLICT (version) DO NOTHING"
            if postgres else
            "INSERT OR IGNORE INTO schema_migrations (version) VALUES (?)",
            ("001_initial_schema",),
        )
        cursor.execute(
            "INSERT INTO schema_migrations (version) VALUES (%s) ON CONFLICT (version) DO NOTHING"
            if postgres else
            "INSERT OR IGNORE INTO schema_migrations (version) VALUES (?)",
            ("003_preserve_legacy_schema",),
        )

        cursor.execute("SELECT version FROM schema_migrations WHERE version = %s" if postgres else
                       "SELECT version FROM schema_migrations WHERE version = ?",
                       ("002_seed_reference_data",))
        seed_version_applied = cursor.fetchone() is not None
        if seed_reference_data and not seed_version_applied:
            courses = [
                ("101", "Python Basics", "Learn the fundamentals of Python programming.", "Python"),
                ("102", "Java Basics", "Learn the fundamentals of Java programming.", "Java"),
                ("103", "HTML & CSS", "Learn the fundamentals of HTML and CSS.", "html and css"),
                ("104", "C Language", "Learn the fundamentals of C programming.", "C language"),
            ]
            course_sql = (
                "INSERT INTO courses (id, name, description, language) VALUES (%s, %s, %s, %s) ON CONFLICT DO NOTHING"
                if postgres else
                "INSERT OR IGNORE INTO courses (id, name, description, language) VALUES (?, ?, ?, ?)"
            )
            cursor.executemany(course_sql, courses)

            # The question bank's insert is conflict-safe and never replaces records.
            from seed_questions import seed
            seed(conn)
            cursor.execute(
                "INSERT INTO schema_migrations (version) VALUES (%s) ON CONFLICT (version) DO NOTHING"
                if postgres else
                "INSERT OR IGNORE INTO schema_migrations (version) VALUES (?)",
                ("002_seed_reference_data",),
            )
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()
